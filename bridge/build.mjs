// Bundles bridge/gas.ts (+ core.ts) into bridge/dist/Code.gs as a plain Apps Script file.
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
mkdirSync(resolve(here, 'dist'), { recursive: true });

await build({
  entryPoints: [resolve(here, 'gas.ts')],
  outfile: resolve(here, 'dist/Code.gs'),
  bundle: true,
  format: 'iife',
  globalName: '__bridge',
  target: 'es2019',
  platform: 'neutral',
  charset: 'ascii',
  legalComments: 'none',
  banner: { js: '// Generated by bridge/build.mjs. Do not edit.' },
  // Apps Script finds triggers/entry points by top-level function declarations.
  footer: {
    js: [
      'function doPost(e) { return __bridge.doPost(e); }',
      'function doGet(e) { return __bridge.doGet(e); }',
      'function onEditInstalled(e) { return __bridge.onEditInstalled(e); }',
      'function setup() { return __bridge.setup(); }',
      'function rotateToken() { return __bridge.rotateToken(); }',
    ].join('\n'),
  },
});
console.log('built bridge/dist/Code.gs');
